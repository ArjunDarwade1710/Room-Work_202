import { DatabaseSync } from 'node:sqlite';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const { Pool } = pg;

const root = path.dirname(
  path.dirname(fileURLToPath(import.meta.url))
);

// Load local .env values if present.
// Never commit .env to GitHub.
const envFile = path.join(root, '.env');

if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);

    if (match && !process.env[match[1]]) {
      process.env[match[1]] = match[2].trim();
    }
  }
}

const sqlitePath =
  process.env.HOMEFLOW_DB_PATH ||
  path.join(root, 'data', 'homeflow.sqlite');

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL is missing from your environment.');
}

if (!existsSync(sqlitePath)) {
  throw new Error(`SQLite database not found: ${sqlitePath}`);
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.PGSSL === 'require'
    ? { rejectUnauthorized: false }
    : undefined
});

let client;
let sqlite;

const tables = [
  'members',
  'settings',
  'duties',
  'changes',
  'claims',
  'water_completions',
  'notifications',
  'audit_log'
];

const schema = `
CREATE TABLE IF NOT EXISTS members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL,
  role TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  active BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS duties (
  id TEXT PRIMARY KEY,
  kind TEXT NOT NULL,
  scheduled_date DATE NOT NULL,
  task_name TEXT NOT NULL,
  original_member TEXT NOT NULL,
  assigned_member TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Upcoming',
  due_at TIMESTAMPTZ NOT NULL,
  completed_at TIMESTAMPTZ,
  completion_entered_at TIMESTAMPTZ,
  completion_known BOOLEAN DEFAULT TRUE,
  cancelled_reason TEXT,
  version INTEGER DEFAULT 1,
  claim_submitted_at TIMESTAMPTZ,
  claim_submitted_by TEXT,
  approval_at TIMESTAMPTZ,
  approval_by TEXT,
  rejection_reason TEXT,
  current_claim_id TEXT,
  weekly_head TEXT,
  window_opens TIMESTAMPTZ,
  window_closes TIMESTAMPTZ,
  created_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ,
  failed_at TIMESTAMPTZ,
  UNIQUE(kind, scheduled_date, task_name)
);

CREATE TABLE IF NOT EXISTS changes (
  id TEXT PRIMARY KEY,
  duty_id TEXT NOT NULL,
  action TEXT NOT NULL,
  previous_value TEXT,
  new_value TEXT,
  reason TEXT,
  actor TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  FOREIGN KEY(duty_id) REFERENCES duties(id)
);

CREATE TABLE IF NOT EXISTS claims (
  id TEXT PRIMARY KEY,
  duty_id TEXT NOT NULL,
  submitted_by TEXT NOT NULL,
  submitted_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL,
  decision_by TEXT,
  decision_at TIMESTAMPTZ,
  rejection_reason TEXT,
  auto_approved BOOLEAN NOT NULL DEFAULT FALSE,
  FOREIGN KEY(duty_id) REFERENCES duties(id)
);

CREATE TABLE IF NOT EXISTS water_completions (
  id TEXT PRIMARY KEY,
  sequence INTEGER UNIQUE NOT NULL,
  member_id INTEGER NOT NULL,
  member_name TEXT NOT NULL,
  completed_at TIMESTAMPTZ NOT NULL,
  FOREIGN KEY(member_id) REFERENCES members(id)
);

CREATE TABLE IF NOT EXISTS notifications (
  id TEXT PRIMARY KEY,
  member TEXT NOT NULL,
  message TEXT NOT NULL,
  kind TEXT NOT NULL,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL,
  duty_id TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
  id TEXT PRIMARY KEY,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  detail TEXT,
  created_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS one_pending_claim_per_duty
ON claims(duty_id)
WHERE status IN (
  'Awaiting Head Approval',
  'Awaiting Admin Review'
);
`;

function getColumns(table) {
  return sqlite
    .prepare(`PRAGMA table_info(${table})`)
    .all()
    .map((column) => column.name);
}

function convertValue(column, value) {
  if (value === undefined) return null;
  if (value === null) return null;

  if (
    ['active', 'completion_known', 'auto_approved'].includes(column)
  ) {
    return Boolean(value);
  }

  return value;
}

try {
  // Open SQLite in read-only mode.
  sqlite = new DatabaseSync(sqlitePath, {
    readOnly: true
  });

  // Use one PostgreSQL connection for the entire transaction.
  client = await pool.connect();

  await client.query('BEGIN');

  await client.query(schema);

  for (const table of tables) {
    const columns = getColumns(table);

    const rows = sqlite
      .prepare(`SELECT * FROM ${table}`)
      .all();

    if (rows.length === 0) {
      console.log(`${table}: no rows to migrate.`);
      continue;
    }

    for (const row of rows) {
      const values = columns.map((column) =>
        convertValue(column, row[column])
      );

      const placeholders = values
        .map((_, index) => `$${index + 1}`)
        .join(', ');

      const conflictColumn =
        table === 'settings' ? 'key' : 'id';

      const updateColumns = columns.filter(
        (column) =>
          column !== conflictColumn &&
          column !== 'id' &&
          column !== 'key'
      );

      const updateClause = updateColumns.length
        ? updateColumns
            .map(
              (column) =>
                `${column} = EXCLUDED.${column}`
            )
            .join(', ')
        : `${conflictColumn} = EXCLUDED.${conflictColumn}`;

      const sql = `
        INSERT INTO ${table} (${columns.join(', ')})
        VALUES (${placeholders})
        ON CONFLICT (${conflictColumn})
        DO UPDATE SET ${updateClause}
      `;

      await client.query(sql, values);
    }

    console.log(`${table}: migrated ${rows.length} rows.`);
  }

  // Keep the members identity sequence ahead of imported IDs.
  await client.query(`
    SELECT setval(
      pg_get_serial_sequence('members', 'id'),
      COALESCE((SELECT MAX(id) FROM members), 1),
      EXISTS (SELECT 1 FROM members)
    )
  `);

  await client.query('COMMIT');

  console.log('Migration completed successfully.');
  console.log(`Source SQLite database: ${sqlitePath}`);
} catch (error) {
  if (client) {
    await client.query('ROLLBACK').catch(() => {});
  }

  console.error('Migration failed:', error.message);
  throw error;
} finally {
  sqlite?.close();

  client?.release();

  await pool.end();
}